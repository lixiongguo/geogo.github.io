# ---------------------------------------------------------------------------
# SDF 定义
# ---------------------------------------------------------------------------

def sd_torus(p: np.ndarray, R: float, r: float) -> np.ndarray:
    """标准环面 SDF。p 形状 (..., 3)。R 为环半径，r 为管半径。

    环面轴线沿 y 轴（即 p[...,1] 方向），孔沿 y 方向贯通。
    """
    q = np.sqrt(p[..., 0] ** 2 + p[..., 2] ** 2) - R
    return np.sqrt(q * q + p[..., 1] ** 2) - r


def _torus_centers(genus: int, R: float, r: float):
    """返回 genus 个沿 z 轴堆叠且相邻相交的环面中心。

    相邻中心距 d = 1.5*r < 2r，保证相邻环面管子相交，min 并集后
    融合为单一连通体，形成 genus 个沿 z 方向的贯通孔。
    """
    d = 1.5 * r
    z0 = -(genus - 1) * d / 2.0
    return [z0 + i * d for i in range(genus)]


def make_torus_sdf(genus: int, R: float = 0.6, r: float = 0.3) -> callable:
    """模式 A：genus 个水平环面沿 z 轴相交堆叠，CSG 并集 (hard min)。

    得到连通的亏格为 genus 的曲面（每个环面贡献一个沿 z 的孔）。
    """
    centers = _torus_centers(genus, R, r)

    def sdf(p: np.ndarray) -> np.ndarray:
        d = np.full(p.shape[:-1], np.inf, dtype=np.float64)
        for c in centers:
            q = p.copy()
            q[..., 2] -= c  # 沿 z 轴平移
            d = np.minimum(d, sd_torus(q, R, r))
        return d

    return sdf


def _smooth_min(a: np.ndarray, b: np.ndarray, k: float = 0.15) -> np.ndarray:
    """多项式光滑并集 (smooth union)。k 控制过渡宽度，k 越小越接近 hard min。"""
    h = np.clip(0.5 + 0.5 * (b - a) / k, 0.0, 1.0)
    return b + h * (a - b) - k * h * (1.0 - h)


def make_analytic_sdf(genus: int, R: float = 0.6, r: float = 0.3) -> callable:
    """模式 B：同样 genus 个环面沿 z 轴相交，但用光滑并集 (smooth union)。

    光滑并集是处处解析（无分段 min）的单一标量场，得到光滑的
    亏格为 genus 曲面，环面相交处平滑过渡（无 CSG 硬接缝）。
    """
    centers = _torus_centers(genus, R, r)

    def sdf(p: np.ndarray) -> np.ndarray:
        d = None
        for c in centers:
            q = p.copy()
            q[..., 2] -= c
            td = sd_torus(q, R, r)
            d = td if d is None else _smooth_min(d, td)
        return d

    return sdf


def make_sdf(mode: str, genus: int):
    if mode == "torus":
        return make_torus_sdf(genus)
    if mode == "analytic":
        return make_analytic_sdf(genus)
    raise ValueError(f"未知 mode: {mode!r}（可选 torus / analytic）")


